describe("prompts — buildParseCvPrompt", () => {
  it("returns a non-empty string for both languages", () => {
    expect(buildParseCvPrompt({ language: "vi" })).toBeTruthy();
    expect(buildParseCvPrompt({ language: "en" })).toBeTruthy();
  });

  it.each(['vi', 'en'] as const)("isolates the %s parse prompt from job descriptions", (language) => {
    // Extra properties from old JavaScript callers must not enter the prompt.
    const legacyParams = { language, jdSection: mockJdSection };
    const result = buildParseCvPrompt(legacyParams);
    expect(result).not.toContain(mockJdSection);
    expect(result).not.toMatch(/\bJD\b|job description|cross-referenc|đối chiếu/i);
    expect(result).toContain(language === 'vi' ? 'Chỉ trích xuất dữ kiện có trong CV' : 'Extract only facts present in the CV');
    expect(result).toContain(language === 'vi' ? 'TẤT CẢ các công việc' : 'ALL work experiences');
    expect(result).toContain(language === 'vi' ? 'ĐÚNG NGÔN NGỮ GỐC' : 'EXACT ORIGINAL LANGUAGE');
  });

  it("contains CV extraction instructions in Vietnamese", () => {
    const result = buildParseCvPrompt({ language: "vi" });
    expect(result).toContain("Kinh nghiệm làm việc");
    expect(result).toContain("technical_skills");
    for (const field of ["relevant_score", "key_match_highlights", "missing_keywords"]) expect(result).not.toContain(field);
    expect(result).toContain("MM/YYYY");
  });

  it("contains CV extraction instructions in English", () => {
    const result = buildParseCvPrompt({ language: "en" });
    expect(result).toContain("Work Experience");
    expect(result).toContain("technical_skills");
    for (const field of ["relevant_score", "key_match_highlights", "missing_keywords"]) expect(result).not.toContain(field);
    expect(result).toContain("MM/YYYY");
  });

  it("defaults to Vietnamese when language is omitted", () => {
    const result = buildParseCvPrompt({});
    expect(result).toContain("Trích xuất");
  });

  // Stage 3.8B/3.9B: canonical analyze is the only CV↔JD judge; parse-cv
  // generates no score, highlights or missing items.
  it("parse schema neither requires nor exposes CV↔JD judgment fields", () => {
    const ats = PARSED_CV_SCHEMA.properties.ats_evaluation;
    for (const field of ["relevant_score", "key_match_highlights", "missing_keywords"]) {
      expect(ats.required).not.toContain(field);
      expect(ats.properties).not.toHaveProperty(field);
    }
    expect(ats.required).toEqual(["years_of_experience"]);
    expect(ats.properties).toEqual({ years_of_experience: { type: 'NUMBER' } });
    expect(PARSED_CV_SCHEMA.required).toEqual([
      'personal_information', 'education', 'work_experience', 'skills', 'projects', 'certifications', 'ats_evaluation',
    ]);
  });
});
describe("prompts — analyze evidence guardrails", () => {
  const cases = [
    {
      lang: "vi",
      build: buildAnalyzePromptVi,
      expectAll: [
        "nguồn dữ kiện DUY NHẤT về ứng viên", // CV = candidate source of truth
        "KHÔNG BAO GIỜ là bằng chứng", // JD != candidate evidence
        "Không tự tính ra số liệu mới", // no invented metrics
        "không thêm kỹ năng hay BẤT KỲ khái niệm nào chỉ có trong JD", // no JD-only skills/concepts in suggestions
        "Nếu bạn thực sự đã sử dụng X", // conditional recommendation
        "KHÁC \"ứng viên không làm được\"", // not evidenced != cannot
        "PostgreSQL không có nghĩa là có BigQuery", // semantic != exact
        "Không thêm kỹ năng/công cụ mới dưới bất kỳ hình thức nào", // skills section
        "Giữ nguyên mọi con số CV đã nêu",
        "KHÔNG đưa gợi ý viết lại cho mục Kỹ năng/Skills",
        "Dữ kiện CV ghi RÕ được ưu tiên hơn giá trị tự tính", // explicit > derived
        "KHÔNG âm thầm sửa",
        "CV ghi \"7 năm\" thì giữ \"7 năm\"",
        // JD-only concepts beyond skills/tools
        "KHÔNG BAO GIỜ cho biết ứng viên ĐÃ LÀM gì",
        "trách nhiệm, phương pháp, quy trình, thuật ngữ nghiệp vụ/lĩnh vực, khái niệm chỉ số",
        "SAI: \"Created Tableau dashboards to track north-star and guardrail metrics\"",
        "không dùng thuật ngữ JD để làm một câu chung chung trong CV trở nên cụ thể hơn",
        "không bao giờ khuyên chèn một từ khóa/thuật ngữ chỉ để tăng điểm ATS",
        "Nếu đây đúng là phương pháp/chỉ số bạn đã sử dụng",
        "Mọi điều kiện (\"nếu bạn đã …\") chỉ được nằm trong \"explanation\"",
        "vẫn là CV tiếng Việt",
        "ĐÚNG NGÔN NGỮ GỐC của CV",
      ],
    },
    {
      lang: "en",
      build: buildAnalyzePromptEn,
      expectAll: [
        "ONLY source of facts about the candidate",
        "NEVER treat the JD as evidence",
        "Do not derive new metrics",
        "never add JD-only skills",
        "If you have actually used X",
        "is NOT \"the candidate cannot do it\"",
        "PostgreSQL in the CV does not mean BigQuery",
        "Never add a new skill/tool in any form",
        "Keep every number the CV states as is",
        "Do NOT make rewrite suggestions for a Skills section",
        "Facts the CV states EXPLICITLY take precedence over derived calculations",
        "do NOT silently reconcile",
        "if it says \"7 years\", keep \"7 years\"",
        "it NEVER tells you what the candidate DID",
        "responsibilities, methodologies, processes, business/domain terminology, metric concepts",
        "WRONG: \"Created Tableau dashboards to track north-star and guardrail metrics\"",
        "never use JD terminology to make a generic CV statement more specific",
        "never recommend inserting a keyword/term merely to improve ATS matching",
        "If you actually used this concept, state the term explicitly",
        "Any condition (\"if you have …\") belongs only in \"explanation\"",
        "is still a Vietnamese CV",
        "EXACT ORIGINAL LANGUAGE of the CV",
      ],
    },
  ] as const;

  for (const { lang, build, expectAll } of cases) {
    describe(lang, () => {
      const p = build({ jdSection: mockJdSection });

      it.each(expectAll)("contains guardrail %s", (phrase) => {
        expect(p).toContain(phrase);
      });

      it("does not show the XYZ template for the model to copy", () => {
        expect(p).not.toMatch(/Accomplished \[X\]|as measured by \[Y\]|by doing \[Z\]/);
      });

      it("maps evidence states onto the existing status enum", () => {
        expect(p).toContain('"matched"');
        expect(p).toContain('"partial"');
        expect(p).toContain('"missing"');
      });

      it("keeps year-only dates as YYYY instead of inventing months", () => {
        expect(p).toMatch(/YYYY/);
        expect(p).not.toMatch(/chuẩn hóa về MM\/YYYY\.|Standardize dates to MM\/YYYY format/);
      });
    });
  }

  it("states the current month only when provided", () => {
    expect(buildAnalyzePrompt({ jdSection: mockJdSection, language: "vi", currentMonth: "10/2026" })).toContain("Thời điểm hiện tại: 10/2026");
    expect(buildAnalyzePrompt({ jdSection: mockJdSection, language: "en", currentMonth: "10/2026" })).toContain("Current month: 10/2026");
    expect(buildAnalyzePromptVi({ jdSection: mockJdSection })).not.toContain("Thời điểm hiện tại");
    // The current month may only fill in durations the CV does not state.
    expect(buildAnalyzePrompt({ jdSection: mockJdSection, language: "vi", currentMonth: "10/2026" })).toContain("không bao giờ dùng để sửa một dữ kiện CV đã ghi");
    expect(buildAnalyzePrompt({ jdSection: mockJdSection, language: "en", currentMonth: "10/2026" })).toContain("never to change a fact the CV states");
  });
});

describe("prompts — logical requirement grouping (Stage 3.12B)", () => {
  const prompt = buildAnalyzePromptEn({ jdSection: mockJdSection });

  it("treats OR alternatives as one logical requirement", () => {
    expect(prompt).toContain("Logical requirement grouping");
    expect(prompt).toContain("BigQuery or Snowflake");
    expect(prompt).toContain("ONE logical requirement");
    expect(prompt).toContain("Preserve the JD's original wording in a single row");
    expect(prompt).toContain("Never emit an unsatisfied alternative as a separate required row");
  });

  it("keeps AND requirements separate", () => {
    expect(prompt).toContain('Requirements joined by "and"');
    expect(prompt).toContain("do not let evidence for one satisfy the other");
  });

  it("does not alter the scoring rubric", () => {
    expect(prompt).toContain("Calculate an overall match score (0-100)");
    expect(prompt).toContain("90-100: FULLY meets all REQUIRED items");
  });
});
