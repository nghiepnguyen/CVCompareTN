import { describe, it, expect } from "vitest";
import { buildAnalyzePrompt, buildAnalyzePromptVi, buildAnalyzePromptEn, buildParseCvPrompt } from "../../services/ai/prompts";

const mockJdSection = "<!-- JD: Senior Frontend Developer -->";

describe("prompts — buildAnalyzePromptVi", () => {
  it("returns a non-empty string", () => {
    const result = buildAnalyzePromptVi({ jdSection: mockJdSection });
    expect(result).toBeTruthy();
    expect(typeof result).toBe("string");
  });

  it("contains the JD section text", () => {
    const result = buildAnalyzePromptVi({ jdSection: mockJdSection });
    expect(result).toContain(mockJdSection);
  });

  it("contains Vietnamese instructions", () => {
    const result = buildAnalyzePromptVi({ jdSection: mockJdSection });
    expect(result).toContain("TIẾNG VIỆT");
    expect(result).toContain("chuyên gia tuyển dụng");
  });

  it("contains key analysis instructions in Vietnamese", () => {
    const result = buildAnalyzePromptVi({ jdSection: mockJdSection });
    expect(result).not.toContain("Google XYZ");
    expect(result).toContain("MM/YYYY");
    expect(result).toContain("detailedComparison");
  });

  it("classifies JD requirements as required vs nice-to-have and requests a formatAssessment", () => {
    const result = buildAnalyzePromptVi({ jdSection: mockJdSection });
    expect(result).toContain("BẮT BUỘC");
    expect(result).toContain("ƯU TIÊN");
    expect(result).toContain("formatAssessment");
    expect(result).toContain("analysisAvailable");
  });

  // fullRewrittenCV and Parsed CV extraction are generated by separate
  // background prompts (buildRewritePromptVi in _server-lib/ai/rewriteService.ts
  // and buildParseCvPrompt below) — not part of the main analyze call.
});

